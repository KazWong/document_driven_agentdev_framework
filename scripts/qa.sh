#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WITH_DOCKER=0
[[ "${1:-}" == "--with-docker" ]] && WITH_DOCKER=1
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
REPORT="$ROOT/docs/qa-report.md"
PASS=()
SKIP=()

run() {
  printf '==> %s\n' "$1"
  shift
  "$@"
  PASS+=("$1")
}

cd "$ROOT"
python3 scripts/qa/validate_tree.py "$ROOT" > "$TMP/tree.json"
PASS+=("Required files, formats, Compose safety invariants, Codex roles, and Humble alignment")
python3 -m compileall -q src scripts tests
PASS+=("Python bytecode compilation")
PYTHONPATH=src python3 -m pytest -q
PASS+=("Python unit and workflow tests")

while IFS= read -r path; do
  bash -n "$path"
done < <(grep -IlR '^#!/usr/bin/env bash' bin scripts docker templates --exclude-dir='__pycache__' || true)
PASS+=("Bash syntax validation")

WORKSPACE="$TMP/workspace"
mkdir -p "$WORKSPACE"
for kind in c cpp python shell; do
  AGENT_WORKSPACE_ROOT="$WORKSPACE" AGENT_STATE_ROOT="$WORKSPACE/.agent-state" ROBOTICS_AGENT_ENV_ROOT="$ROOT" \
    "$ROOT/bin/projectctl" create --type "$kind" --name "qa-$kind" >/dev/null
done
PASS+=("C11, C++20, Python, and Bash project generation with initial Git commits")

(cd "$WORKSPACE/projects/qa-c" && ./scripts/ci/verify.sh)
PASS+=("Generated C11 Debug and sanitizer builds")
(cd "$WORKSPACE/projects/qa-cpp" && ./scripts/ci/verify.sh)
PASS+=("Generated C++20 Debug and sanitizer builds")
(cd "$WORKSPACE/projects/qa-python" && PYTHONPATH=src python3 -m pytest -q)
PASS+=("Generated Python tests")
bash -n "$WORKSPACE/projects/qa-shell/bin/qa-shell" "$WORKSPACE/projects/qa-shell/scripts/ci/verify.sh"
if command -v shellcheck >/dev/null 2>&1 && command -v bats >/dev/null 2>&1; then
  (cd "$WORKSPACE/projects/qa-shell" && ./scripts/ci/verify.sh)
  PASS+=("Generated Bash ShellCheck and Bats tests")
else
  SKIP+=("Generated Bash ShellCheck/Bats execution (tools unavailable on packaging host; installed in Docker images)")
fi

AGENT_WORKSPACE_ROOT="$WORKSPACE" ROBOTICS_AGENT_ENV_ROOT="$ROOT" "$ROOT/bin/testctl" list >/dev/null
AGENT_WORKSPACE_ROOT="$WORKSPACE" ROBOTICS_AGENT_ENV_ROOT="$ROOT" "$ROOT/bin/testctl" --dry-run test ros2-gazebo "$WORKSPACE/projects/qa-cpp" -- --clean >/dev/null
PASS+=("testctl registry, alias, and delegated Humble command generation")

if [[ "$WITH_DOCKER" -eq 1 ]]; then
  command -v docker >/dev/null 2>&1 || { echo "Docker requested but unavailable" >&2; exit 1; }
  docker compose -f compose.yaml config --quiet
  docker compose -f compose.yaml --profile test build
  docker compose -f compose.yaml --profile test run --rm generic-test generic-test smoke
  docker compose -f compose.yaml --profile test run --rm firmware-test firmware-test smoke
  PASS+=("Docker Compose rendering, image builds, and generic/firmware smoke tests")
else
  SKIP+=("Live Docker image builds and container smoke tests (run scripts/qa.sh --with-docker on a Docker host)")
fi

{
  printf '# QA report\n\n'
  printf 'Release: **2.0.1**\n\n'
  printf 'Generated by `scripts/qa.sh`.\n\n'
  printf '## Passed\n\n'
  for item in "${PASS[@]}"; do printf -- '- %s\n' "$item"; done
  printf '\n## Not executed in this run\n\n'
  if [[ ${#SKIP[@]} -eq 0 ]]; then printf -- '- None\n'; else for item in "${SKIP[@]}"; do printf -- '- %s\n' "$item"; done; fi
  printf '\nNo physical robotics hardware was accessed.\n'
} > "$REPORT"
printf 'QA passed. Report: %s\n' "$REPORT"
